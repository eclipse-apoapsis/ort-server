package org.eclipse.apoapsis.ortserver.components.provenancefilestorage

import org.eclipse.apoapsis.ortserver.storage.Key

import org.ossreviewtoolkit.model.ArtifactProvenance
import org.ossreviewtoolkit.model.KnownProvenance
import org.ossreviewtoolkit.model.RepositoryProvenance

/** The prefix of storage keys for [ArtifactProvenance]s. */
private const val SOURCE_ARTIFACT_PREFIX = "source-artifact"

/** The prefix of storage keys for [RepositoryProvenance]s. */
private const val VCS_PREFIX = "vcs"

/** The separator between the components of a storage key. */
private const val SEPARATOR = "|"

/** A regular expression to extract the value and the algorithm from the string representation of a hash. */
private val hashRegex = Regex("""^Hash\(value=(.*), algorithm=(.*)\)$""")

/**
 * Generate the storage [Key] under which data for this [KnownProvenance] is stored in a provenance file storage. The
 * key has the format `source-artifact|<url>|<hash>` for artifact provenances and `vcs|<type>|<url>|<revision>` for
 * repository provenances.
 */
internal fun KnownProvenance.toStorageKey(): Key =
    when (this) {
        is ArtifactProvenance -> Key("$SOURCE_ARTIFACT_PREFIX|${sourceArtifact.url}|${sourceArtifact.hash}")
        is RepositoryProvenance -> Key("$VCS_PREFIX|${vcsInfo.type}|${vcsInfo.url}|$resolvedRevision")
    }

/** The information about a provenance that can be restored from a storage key generated by [toStorageKey]. */
internal sealed interface ParsedProvenanceKey {
    /** The URL of the source artifact or the repository. */
    val url: String

    /** The information restored from the key of an [ArtifactProvenance]. */
    data class SourceArtifact(
        override val url: String,

        /** The value of the hash of the source artifact. */
        val hashValue: String,

        /** The algorithm of the hash of the source artifact, or *null* if it could not be determined. */
        val hashAlgorithm: String?
    ) : ParsedProvenanceKey

    /** The information restored from the key of a [RepositoryProvenance]. */
    data class Vcs(
        override val url: String,

        /** The type of the VCS. */
        val vcsType: String,

        /** The resolved revision. */
        val revision: String
    ) : ParsedProvenanceKey
}

/**
 * Parse the given [key] that was generated by [toStorageKey] and return the contained information about the
 * provenance, or *null* if the key does not have the expected format. As the URL may contain the separator character
 * itself, it is determined as everything between the leading and the trailing components of the key.
 */
internal fun parseStorageKey(key: Key): ParsedProvenanceKey? {
    val parts = key.key.split(SEPARATOR)

    return when (parts.first()) {
        SOURCE_ARTIFACT_PREFIX -> parts.takeIf { it.size >= 3 }?.let {
            val hash = it.last()
            val hashMatch = hashRegex.matchEntire(hash)

            ParsedProvenanceKey.SourceArtifact(
                url = it.subList(1, it.lastIndex).joinToString(SEPARATOR),
                hashValue = hashMatch?.groupValues?.get(1) ?: hash,
                hashAlgorithm = hashMatch?.groupValues?.get(2)?.takeUnless { algorithm -> algorithm.isEmpty() }
            )
        }

        VCS_PREFIX -> parts.takeIf { it.size >= 4 }?.let {
            ParsedProvenanceKey.Vcs(
                url = it.subList(2, it.lastIndex).joinToString(SEPARATOR),
                vcsType = it[1],
                revision = it.last()
            )
        }

        else -> null
    }
}
