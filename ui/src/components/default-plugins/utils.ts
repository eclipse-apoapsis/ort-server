/**
 * Map the configured plugin ids to the ids of the available plugins. Plugin ids are matched
 * case-insensitively by the backend, so an id that only differs in case from an available plugin,
 * for example a reporter that is replaced by a report definition, refers to that plugin. Exact
 * matches take precedence, ids without a match are kept, and duplicates are removed.
 */
export function normalizePluginIds(
  pluginIds: readonly string[],
  availablePlugins: readonly PreconfiguredPluginDescriptor[]
): string[] {
  const availablePluginIds = availablePlugins.map((plugin) => plugin.id);
  const normalizedIds = pluginIds.map(
    (pluginId) =>
      availablePluginIds.find((id) => id === pluginId) ??
      availablePluginIds.find(
        (id) => id.toLowerCase() === pluginId.toLowerCase()
      ) ??
      pluginId
  );

  return normalizedIds.filter(
    (pluginId, index) =>
      normalizedIds.findIndex(
        (id) => id.toLowerCase() === pluginId.toLowerCase()
      ) === index
  );
}

/**
 * Get descriptors for the configured plugin ids that are not among the available plugins, for
 * example because the plugins were disabled after they were configured as defaults.
 */
export function getUnavailablePlugins(
  pluginType: PluginType,
  pluginIds: readonly string[],
  availablePlugins: readonly PreconfiguredPluginDescriptor[]
): PreconfiguredPluginDescriptor[] {
  const availablePluginIds = new Set(
    availablePlugins.map((plugin) => plugin.id)
  );

  return pluginIds
    .filter((pluginId) => !availablePluginIds.has(pluginId))
    .map((pluginId) => ({
      id: pluginId,
      type: pluginType,
      displayName: pluginId,
      summary:
        '**This plugin is not available.** It is ignored when the defaults are applied.',
      options: [],
    }));
}

/** Check whether two lists of plugin ids differ, taking the order into account only if it matters. */
export function pluginIdsDiffer(
  a: readonly string[],
  b: readonly string[],
  isOrdered: boolean
) {
  if (a.length !== b.length) return true;

  if (isOrdered) return a.some((pluginId, index) => pluginId !== b[index]);

  const bSet = new Set(b);
  return a.some((pluginId) => !bSet.has(pluginId));
}
