type HelpDocumentEntry = {
  title: string;
  sections: Record<string, string>;
};

/** Return whether the given file name is a help document. */
const isHelpDocument = (fileName: string) =>
  fileName.endsWith('.md') && fileName !== 'README.md';

// The parts of a Markdown syntax tree node that the script reads.
type MarkdownNode = {
  type: string;
  depth?: number;
  url?: string;
  value?: string;
  children?: MarkdownNode[];
};

// The explicit ID at the end of a heading, as the help panel reads it, see remark-heading-ids.ts.
const HEADING_ID = /\s*\{#([\w-]+)\}\s*$/;

// Parse Markdown like the help panel does, so that the script sees the same headings and links.
const parseMarkdown = (markdown: string): MarkdownNode =>
  fromMarkdown(markdown);

/** Return the nodes of the given type in the tree below the given node. */
const findNodes = (node: MarkdownNode, type: string): MarkdownNode[] => [
  ...(node.type === type ? [node] : []),
  ...(node.children ?? []).flatMap((child) => findNodes(child, type)),
];

/** Return the text of a node without its formatting. */
const textOf = (node: MarkdownNode): string =>
  node.value ?? (node.children ?? []).map(textOf).join('');

/** Read the title and the sections with an explicit ID from the Markdown text of a help document. */
export const parseHelpDocument = (
  fileName: string,
  markdown: string
): HelpDocumentEntry => {
  const headings = findNodes(parseMarkdown(markdown), 'heading');
  const titleHeading = headings.find((heading) => heading.depth === 1);
  const title = titleHeading && textOf(titleHeading).trim();

  if (!title) {
    throw new Error(
      `The help document '${fileName}' has no level one heading.`
    );
  }

  const sections: Record<string, string> = {};

  for (const heading of headings) {
    const last = heading.children?.at(-1);
    const id =
      heading.depth !== 1 && last?.type === 'text'
        ? HEADING_ID.exec(last.value ?? '')?.[1]
        : undefined;

    if (id === undefined) continue;

    if (id in sections) {
      throw new Error(
        `The help document '${fileName}' has more than one section '${id}'.`
      );
    }

    sections[id] = textOf(heading).replace(HEADING_ID, '').trim();
  }

  return { title, sections };
};

/** Generate the formatted content of the help index from the help documents in the given directory. */
export const generateHelpIndex = async (helpDir = HELP_DIR) => {
  const index: Record<string, HelpDocumentEntry> = {};

  for (const fileName of readdirSync(helpDir).filter(isHelpDocument).sort()) {
    index[fileName.slice(0, -'.md'.length)] = parseHelpDocument(
      fileName,
      readFileSync(join(helpDir, fileName), 'utf8')
    );
  }

  const source = [
    LICENSE_HEADER,
    '',
    '// Generated by `pnpm generate:help` from the help documents in this directory. Do not edit.',
    '',
    `export const helpIndex = ${JSON.stringify(index)} as const;`,
    '',
  ].join('\n');

  return format(source, {
    ...(await resolveConfig(HELP_INDEX_FILE)),
    filepath: HELP_INDEX_FILE,
  });
};

/** Read the committed help index, or return undefined if it does not exist. */
export const readHelpIndex = () => {
  try {
    return readFileSync(HELP_INDEX_FILE, 'utf8');
  } catch {
    return undefined;
  }
};

/** Write the help index, unless it is up to date. Return whether it was written. */
export const writeHelpIndex = async () => {
  const content = await generateHelpIndex();

  if (content === readHelpIndex()) return false;

  writeFileSync(HELP_INDEX_FILE, content);

  return true;
};

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  try {
    await writeHelpIndex();
  } catch (error) {
    process.stderr.write(
      `${error instanceof Error ? error.message : String(error)}\n`
    );
    process.exitCode = 1;
  }
}
